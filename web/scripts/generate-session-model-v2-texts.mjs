// UX-11A.5c.4 — regenerates the web mirror of the Session Model V2 coaching
// texts (planning-engine coachingTextCatalog, fr-CH) that the read-only V2
// renderer resolves by versioned id. The web never imports engine source at
// runtime (Vite file boundary), so the texts are mirrored, never hand-written;
// coachingTextsV1_0.generated.test.ts fails if the mirror drifts.
//
// Usage (from web/): node scripts/generate-session-model-v2-texts.mjs
// Requires planning-engine to be built (cd ../planning-engine && npm run build).
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const catalog = await import(pathToFileURL(join(here, "..", "..", "planning-engine", "dist", "catalog", "coachingTextCatalog.js")).href);

const version = catalog.COACHING_TEXT_CATALOG_VERSION;
if (version !== "coaching-text-v1.0") throw new Error(`expected coaching-text-v1.0, got ${version}: add a new mirror instead of overwriting this one`);

const entries = [...catalog.COACHING_TEXT_CATALOG_ENTRIES].sort((a, b) => (a.id < b.id ? -1 : 1));
const lines = entries.map((e) => `  ${JSON.stringify(e.id)}: { kind: ${JSON.stringify(e.kind)}, text: ${JSON.stringify(e.text["fr-CH"])} },`);
const out = `// GENERATED by web/scripts/generate-session-model-v2-texts.mjs — do not edit.
// Source: planning-engine/src/catalog/coachingTextCatalog.ts, ${version}, locale fr-CH.
// Content PROVISIONAL — coaching validation required (see the engine catalogue).

export const COACHING_TEXTS_V1_0_VERSION = ${JSON.stringify(version)};

export type CoachingTextKindV1_0 = "cue" | "success_criterion" | "vigilance" | "instruction" | "intent";

export const COACHING_TEXTS_V1_0: Readonly<Record<string, { kind: CoachingTextKindV1_0; text: string }>> = {
${lines.join("\n")}
};
`;
writeFileSync(join(here, "..", "src", "features", "finalPrescriptionV2", "coachingTextsV1_0.generated.ts"), out);
console.log(`wrote ${entries.length} texts (${version})`);
